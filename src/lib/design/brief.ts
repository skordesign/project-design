/**
 * The markdown brief: the main thing coding agents read. Deterministic, complete and compact.
 */
import { buildPlan } from "@/lib/design/build-plan";
import { ARCHITECTURE_STYLE_DESCRIPTIONS } from "@/lib/design/catalog";
import { dataModel, type DataModelEntity } from "@/lib/design/datamodel";
import { indexDesign, type DesignIndex } from "@/lib/design/graph";
import type {
  DesignDocument,
  DesignNode,
  EnvVar,
  Field,
  NodeOfKind,
  Parameter,
  TypeShape,
} from "@/lib/design/schema";
import type { ComponentStatus } from "@/lib/design/status";

export interface BriefInput {
  project: { name: string; slug: string; description: string };
  document: DesignDocument;
  revision: number;
  version: { number: number; label: string } | null;
  statuses?: Map<string, ComponentStatus>;
}

// ── Type formatting (exported for reuse) ────────────────────────────────────

export function formatFieldType(field: Field, index: DesignIndex): string {
  let base: string;
  if (field.type === "enum") base = `enum(${field.enumValues.join("|")})`;
  else if (field.type === "ref") {
    base = (field.refEntityId && index.node(field.refEntityId)?.name) || "ref";
  } else base = field.type;
  return field.list ? `${base}[]` : base;
}

const inlineFields = (fields: Field[], index: DesignIndex) =>
  `{ ${fields.map((f) => `${f.name}${f.required ? "" : "?"}: ${formatFieldType(f, index)}`).join(", ")} }`;

export function formatShape(shape: TypeShape | null, index: DesignIndex): string {
  if (!shape) return "—";
  if (shape.entityId) {
    const name = index.node(shape.entityId)?.name ?? shape.entityId;
    return shape.list ? `${name}[]` : name;
  }
  if (shape.fields.length === 0) return "—";
  const inline = inlineFields(shape.fields, index);
  return shape.list ? `${inline}[]` : inline;
}

// ── Helpers ─────────────────────────────────────────────────────────────────

const oneLine = (text: string) => text.replace(/\s+/g, " ").trim();
const cell = (text: string) => oneLine(text).replace(/\|/g, "\\|");
const table = (header: string[], rows: string[][]) => [
  `| ${header.join(" | ")} |`,
  `| ${header.map(() => "---").join(" | ")} |`,
  ...rows.map((r) => `| ${r.map(cell).join(" | ")} |`),
];
const count = (n: number, noun: string) => `${n} ${noun}${n === 1 ? "" : "s"}`;
const yesNo = (b: boolean) => (b ? "yes" : "no");

const TOP_LEVEL_ORDER = ["service", "datastore", "api", "queue", "integration", "actor"] as const;
const GAME_ORDER = ["loop", "system", "resource", "content"] as const;

/** "Dodge cost = 25 stamina (notes)" */
const formatParameter = (p: Parameter) =>
  `${p.name}${p.value ? ` = ${p.value}${p.unit ? ` ${p.unit}` : ""}` : ""}${
    p.notes.trim() ? ` (${oneLine(p.notes)})` : ""
  }`;
const CARDINALITY_LABEL = { "one-to-one": "1—1", "one-to-many": "1—N", "many-to-many": "N—N" };

// ── Renderer ────────────────────────────────────────────────────────────────

export function renderBrief(input: BriefInput): string {
  const { project, document: doc, revision, version, statuses } = input;
  const index = indexDesign(doc);
  const name = (id: string) => index.node(id)?.name ?? id;
  const names = (ids: string[]) => ids.map(name).join(", ");
  const out: string[] = [];
  const section = (title: string, body: string[]) => {
    if (body.length > 0) out.push(`## ${title}`, "", ...body, "");
  };

  out.push(
    `# ${project.name} — design brief`,
    `> project \`${project.slug}\` · ${
      version
        ? `version ${version.number}${version.label ? ` (${version.label})` : ""}`
        : `draft revision ${revision}`
    } · generated by Project Designer`,
    "> Ids in [brackets] are stable. Use them with get_component, get_api_contract and set_component_status.",
    "> MUST conventions and layer rules are hard constraints.",
    "",
  );
  if (project.description.trim()) out.push(project.description.trim(), "");

  // Overview (always present)
  const o = doc.overview;
  const overview: string[] = [];
  if (o.summary.trim()) overview.push(o.summary.trim(), "");
  if (o.goals.length > 0) overview.push("**Goals**", ...o.goals.map((g) => `- ${g}`), "");
  if (o.nonGoals.length > 0) overview.push("**Non-goals**", ...o.nonGoals.map((g) => `- ${g}`), "");
  overview.push(
    `**Architecture style:** ${o.architectureStyle} — ${ARCHITECTURE_STYLE_DESCRIPTIONS[o.architectureStyle]}`,
  );
  if (o.architectureNotes.trim()) overview.push("", o.architectureNotes.trim());
  const repo = [o.repository.layout, o.repository.packageManager].filter(Boolean).join(", ");
  overview.push(
    "",
    `**Repository:** ${repo}${o.repository.notes.trim() ? ` — ${oneLine(o.repository.notes)}` : ""}`,
  );
  out.push("## Overview", "", ...overview, "");

  // Game vision (game mode only)
  if (o.mode === "game") {
    const g = o.game;
    const vision: string[] = [];
    const facts = [
      g.genre && `**Genre:** ${g.genre}`,
      g.engine && `**Engine:** ${g.engine}`,
      g.platforms.length > 0 && `**Platforms:** ${g.platforms.join(", ")}`,
    ].filter(Boolean) as string[];
    if (facts.length > 0) vision.push(facts.join(" · "), "");
    if (g.pillars.length > 0)
      vision.push("**Design pillars**", ...g.pillars.map((p) => `- ${p}`), "");
    if (g.parameters.length > 0) {
      vision.push(
        "**Design parameters**",
        "",
        ...table(
          ["Parameter", "Value", "Notes"],
          g.parameters.map((p) => [p.name, [p.value, p.unit].filter(Boolean).join(" "), p.notes]),
        ),
        "",
      );
    }
    if (g.references.length > 0) {
      vision.push(
        "**References**",
        ...g.references.map(
          (r) => `- ${r.name}${r.takeaway.trim() ? `: ${oneLine(r.takeaway)}` : ""}`,
        ),
        "",
      );
    }
    if (g.targets.length > 0) {
      vision.push(
        "**Targets**",
        "",
        ...table(
          ["Target", "Value", "Notes"],
          g.targets.map((p) => [p.name, [p.value, p.unit].filter(Boolean).join(" "), p.notes]),
        ),
        "",
      );
    }
    section("Game vision", vision.slice(0, -1));
  }

  // Tech stack
  section(
    "Tech stack",
    doc.stack.length === 0
      ? []
      : table(
          ["Category", "Choice", "Version", "Applies to", "Notes"],
          doc.stack.map((s) => [
            s.category,
            s.name,
            s.version,
            s.scope.length > 0 ? names(s.scope) : "everything",
            s.notes,
          ]),
        ),
  );

  // Conventions
  const conventions: string[] = [];
  for (const level of ["must", "should", "may"] as const) {
    const items = doc.conventions.filter((c) => c.level === level);
    if (items.length === 0) continue;
    conventions.push(
      `### ${level.toUpperCase()}`,
      "",
      ...items.map(
        (c) =>
          `- [${c.id}] (${c.category}) ${oneLine(c.rule)}${c.scope.length > 0 ? ` — applies to: ${names(c.scope)}` : ""}`,
      ),
      "",
    );
  }
  if (conventions.length > 0) section("Conventions", conventions.slice(0, -1));

  // Components
  const statusOf = (id: string) => statuses?.get(id);
  const components: string[] = [];
  const renderNode = (n: DesignNode, depth: number) => {
    const pad = "  ".repeat(depth);
    const bits = [n.kind, ...nodeFacts(n)];
    const status = statusOf(n.id);
    components.push(
      `${pad}- **${n.name}** [${n.id}] — ${bits.join(" · ")}${status ? ` · status: ${status}` : ""}`,
    );
    const details: string[] = [];
    if (n.description.trim()) details.push(oneLine(n.description));
    details.push(...nodeLists(n));
    if (n.tags.length > 0) details.push(`Tags: ${n.tags.join(", ")}`);
    if (n.patterns.length > 0) {
      details.push(
        `Patterns: ${n.patterns.map((p) => (p.notes ? `${p.name} (${oneLine(p.notes)})` : p.name)).join(", ")}`,
      );
    }
    const relations = nodeRelations(index, n);
    if (relations.length > 0) details.push(relations.join(" · "));
    for (const d of details) components.push(`${pad}  - ${d}`);
    for (const child of index.children(n.id))
      if (child.kind !== "note") renderNode(child, depth + 1);
  };
  const order =
    o.mode === "game" ? [...GAME_ORDER, ...TOP_LEVEL_ORDER] : [...TOP_LEVEL_ORDER, ...GAME_ORDER];
  for (const kind of order) {
    for (const n of index.children(null)) if (n.kind === kind) renderNode(n, 0);
  }
  out.push(
    "## Components",
    "",
    ...(components.length > 0 ? components : ["_No components yet._"]),
    "",
  );

  // Economy: every resource with its sources and sinks
  const resources = doc.nodes.filter((n) => n.kind === "resource");
  const flow = (id: string, kind: "produces" | "consumes") =>
    index
      .incoming(id, kind)
      .map((e) => {
        const detail =
          e.kind === "produces" ? e.data.rate : e.kind === "consumes" ? e.data.amount : "";
        return `${name(e.source)}${detail ? ` (${detail})` : ""}`;
      })
      .join(", ");
  section(
    "Economy",
    resources.length === 0
      ? []
      : table(
          ["Resource", "Type", "Initial", "Range", "Regen", "Sources", "Sinks"],
          resources.map((r) => [
            `${r.name} [${r.id}]`,
            r.data.type,
            r.data.initial,
            [r.data.min, r.data.max].some(Boolean)
              ? `${r.data.min || "—"}…${r.data.max || "—"}`
              : "",
            r.data.regen,
            flow(r.id, "produces") || "—",
            flow(r.id, "consumes") || "—",
          ]),
        ),
  );

  // Content tables
  const contents: string[] = [];
  for (const n of doc.nodes) {
    if (n.kind !== "content") continue;
    contents.push(
      `### ${n.name} [${n.id}] — ${n.data.type}${n.parentId ? ` · in ${name(n.parentId)}` : ""}`,
      "",
    );
    if (n.description.trim()) contents.push(oneLine(n.description), "");
    if (n.data.columns.length > 0) {
      const width = n.data.columns.length;
      contents.push(
        ...table(
          n.data.columns,
          n.data.rows.map((r) => Array.from({ length: width }, (_, i) => r[i] ?? "")),
        ),
      );
    } else contents.push("_No columns yet._");
    contents.push("");
  }
  if (contents.length > 0) section("Content tables", contents.slice(0, -1));

  // Data model
  const model = dataModel(index);
  const entityBlock = (e: DataModelEntity, level: string) => {
    const lines = [`${level} ${e.name} [${e.id}]`, ""];
    if (e.description.trim()) lines.push(oneLine(e.description), "");
    if (e.fields.length > 0) {
      lines.push(
        ...table(
          ["Field", "Type", "Required", "Unique", "Default", "Notes"],
          e.fields.map((f) => [
            f.name,
            formatFieldType(f, index),
            yesNo(f.required),
            f.unique || f.primary ? "yes" : "",
            f.default !== null ? `\`${f.default}\`` : "",
            [f.primary ? "primary key" : "", oneLine(f.description)].filter(Boolean).join("; "),
          ]),
        ),
        "",
      );
    }
    if (e.indexes.length > 0) {
      lines.push(
        "Indexes:",
        ...e.indexes.map((i) => `- (${i.fields.join(", ")})${i.unique ? " unique" : ""}`),
        "",
      );
    }
    const relations = model.relations.filter((r) => r.from.id === e.id);
    if (relations.length > 0) {
      lines.push(
        ...relations.map((r) => {
          const extras = [
            r.required ? "required" : "",
            r.onDelete !== "no-action" ? `on delete ${r.onDelete.replace("-", " ")}` : "",
          ].filter(Boolean);
          return (
            `- ${r.from.name} ${CARDINALITY_LABEL[r.cardinality]} ${r.to.name}` +
            (r.foreignKey ? ` via ${r.to.name}.${r.foreignKey}` : "") +
            (extras.length > 0 ? ` (${extras.join(", ")})` : "")
          );
        }),
        "",
      );
    }
    return lines;
  };
  const data: string[] = [];
  for (const ds of model.datastores) {
    const store = index.node(ds.id) as NodeOfKind<"datastore">;
    data.push(
      `### ${ds.name} [${ds.id}] — ${[ds.engine, ds.version].filter(Boolean).join(" ")}${store.data.purpose ? ` — ${oneLine(store.data.purpose)}` : ""}`,
      "",
    );
    for (const e of ds.entities) data.push(...entityBlock(e, "####"));
  }
  if (model.domainModels.length > 0) {
    data.push("### Domain models", "");
    for (const e of model.domainModels) data.push(...entityBlock(e, "####"));
  }
  if (data.length > 0) section("Data model", data.slice(0, -1));

  // APIs
  const apis: string[] = [];
  for (const n of doc.nodes) {
    if (n.kind !== "api") continue;
    const implementers = index.incoming(n.id, "exposes").map((e) => {
      const ops = e.data.operations
        .map((id) => n.data.operations.find((o) => o.id === id)?.name)
        .filter(Boolean);
      return `${name(e.source)}${ops.length > 0 ? ` (${ops.join(", ")})` : ""}`;
    });
    const consumers = index.incoming(n.id, "calls").map((e) => name(e.source));
    const meta = [
      n.data.style,
      n.data.basePath && `base ${n.data.basePath}`,
      n.data.version && `version ${n.data.version}`,
      `auth ${n.data.auth}`,
      implementers.length > 0 && `implemented by: ${[...new Set(implementers)].join(", ")}`,
      consumers.length > 0 && `consumed by: ${[...new Set(consumers)].join(", ")}`,
    ].filter(Boolean);
    apis.push(`### ${n.name} [${n.id}] — ${meta.join(" · ")}`, "");
    if (n.data.operations.length > 0) {
      apis.push(
        ...table(
          ["Operation", "Method", "Path", "Request", "Response", "Errors"],
          n.data.operations.map((op) => [
            `\`${op.name}\` [${op.id}]${op.auth !== "inherit" ? ` (auth: ${op.auth})` : ""}${op.summary ? ` — ${oneLine(op.summary)}` : ""}`,
            op.method ?? "—",
            op.path ? `\`${op.path}\`` : "—",
            formatShape(op.request, index),
            formatShape(op.response, index),
            op.errors
              .map((e) => `${e.status}${e.description ? ` ${oneLine(e.description)}` : ""}`)
              .join("; ") || "—",
          ]),
        ),
        "",
      );
    }
  }
  if (apis.length > 0) section("APIs", apis.slice(0, -1));

  // Messaging
  const messaging: string[] = [];
  for (const n of doc.nodes) {
    if (n.kind !== "queue") continue;
    messaging.push(`### ${n.name} [${n.id}] — ${n.data.technology}`, "");
    const sources = (kind: "publishes" | "subscribes", channelId: string) => [
      ...new Set(
        index
          .incoming(n.id, kind)
          .filter(
            (e) =>
              "channelId" in e.data &&
              (e.data.channelId === null || e.data.channelId === channelId),
          )
          .map((e) => name(e.source)),
      ),
    ];
    for (const ch of n.data.channels) {
      const producers = sources("publishes", ch.id);
      const consumers = sources("subscribes", ch.id);
      messaging.push(
        `- \`${ch.name}\` [${ch.id}] — payload ${formatShape(ch.payload, index)} · producers: ${producers.join(", ") || "none"} · consumers: ${consumers.join(", ") || "none"}`,
      );
    }
    messaging.push("");
  }
  if (messaging.length > 0) section("Messaging", messaging.slice(0, -1));

  // Integrations
  const integrations: string[] = [];
  for (const n of doc.nodes) {
    if (n.kind !== "integration") continue;
    const users = index.incoming(n.id, "uses");
    const meta = [
      n.data.category,
      n.data.sdk && `sdk \`${n.data.sdk}\``,
      n.data.docsUrl && `docs ${n.data.docsUrl}`,
      users.length > 0 && `used by: ${[...new Set(users.map((e) => name(e.source)))].join(", ")}`,
    ].filter(Boolean);
    integrations.push(
      `### ${n.data.provider || n.name} [${n.id}] — ${meta.join(" · ")}${n.data.purpose ? ` — ${oneLine(n.data.purpose)}` : ""}`,
      "",
    );
  }
  if (integrations.length > 0) section("Integrations", integrations.slice(0, -1));

  // Environment
  const envRows: string[][] = [];
  const envOf = (owner: string, env: EnvVar[]) => {
    for (const v of env) {
      envRows.push([
        owner,
        `\`${v.name}\``,
        yesNo(v.required),
        yesNo(v.secret),
        v.description,
        v.example,
      ]);
    }
  };
  for (const n of doc.nodes) {
    if (n.kind === "service" || n.kind === "integration") envOf(n.name, n.data.env);
  }
  if (envRows.length > 0) {
    section(
      "Environment",
      table(
        ["Service/Integration", "Variable", "Required", "Secret", "Description", "Example"],
        envRows,
      ),
    );
  }

  // Actors
  const actors = doc.nodes
    .filter((n): n is NodeOfKind<"actor"> => n.kind === "actor")
    .map((n) => {
      const goals = n.data.goals.length > 0 ? ` — ${n.data.goals.join("; ")}` : "";
      const interacts = index
        .outgoing(n.id, "interacts")
        .map((e) => `${name(e.target)}${e.data.via ? ` via ${e.data.via}` : ""}`);
      return `- ${n.name} [${n.id}] (${n.data.type})${goals}${interacts.length > 0 ? `; interacts with ${interacts.join(", ")}` : ""}`;
    });
  section("Actors", actors);

  // Decisions
  const decisions: string[] = [];
  for (const d of doc.decisions) {
    decisions.push(`### [${d.id}] ${d.title} — ${d.status}${d.date ? ` · ${d.date}` : ""}`, "");
    if (d.context.trim()) decisions.push(`**Context.** ${d.context.trim()}`, "");
    if (d.decision.trim()) decisions.push(`**Decision.** ${d.decision.trim()}`, "");
    if (d.consequences.trim()) decisions.push(`**Consequences.** ${d.consequences.trim()}`, "");
  }
  if (decisions.length > 0) section("Decisions", decisions.slice(0, -1));

  // Roadmap
  const roadmap: string[] = [];
  for (const m of doc.milestones) {
    roadmap.push(`### [${m.id}] ${m.title}${m.timeframe ? ` — ${m.timeframe}` : ""}`, "");
    roadmap.push(...m.deliverables.map((d) => `- ${d}`));
    if (m.exitCriteria.trim()) roadmap.push(`- **Exit criteria:** ${oneLine(m.exitCriteria)}`);
    if (m.scope.length > 0) roadmap.push(`- **Builds:** ${names(m.scope)}`);
    roadmap.push("");
  }
  if (roadmap.length > 0) section("Roadmap", roadmap.slice(0, -1));

  // Notes
  section(
    "Notes",
    doc.nodes
      .filter((n) => n.kind === "note")
      .map(
        (n) =>
          `- ${n.name} [${n.id}]${n.parentId ? ` (in ${name(n.parentId)})` : ""}: ${oneLine(n.description)}`,
      ),
  );

  // Build order
  const steps = buildPlan(index, statuses);
  section(
    "Build order",
    steps.map(
      (s) =>
        `${s.order}. [${s.id}] ${s.title}${s.dependsOn.length > 0 && s.id !== "setup" ? ` — after: ${s.dependsOn.join(", ")}` : ""}`,
    ),
  );

  return out.join("\n").trimEnd() + "\n";
}

function nodeFacts(n: DesignNode): string[] {
  switch (n.kind) {
    case "service": {
      const stack = [n.data.language, n.data.framework, n.data.runtime].filter(Boolean).join(" / ");
      return [
        n.data.type,
        stack,
        n.data.path && `\`${n.data.path}\``,
        n.data.port !== null && `port ${n.data.port}`,
      ].filter(Boolean) as string[];
    }
    case "layer":
    case "module":
      return n.data.path ? [`\`${n.data.path}\``] : [];
    case "entity":
      return [count(n.data.fields.length, "field")];
    case "datastore":
      return [[n.data.engine, n.data.version].filter(Boolean).join(" ")];
    case "api":
      return [n.data.style, count(n.data.operations.length, "operation")];
    case "integration":
      return [n.data.provider, n.data.category].filter(Boolean);
    case "queue":
      return [n.data.technology, count(n.data.channels.length, "channel")];
    case "actor":
      return [n.data.type];
    case "loop":
      return n.data.duration ? [n.data.duration] : [];
    case "system":
      return [
        n.data.category,
        n.data.authority !== "unspecified" && `${n.data.authority}-authoritative`,
        `priority ${n.data.priority}`,
      ].filter(Boolean) as string[];
    case "mechanic":
      return [n.data.trigger && `trigger: ${n.data.trigger}`, `priority ${n.data.priority}`].filter(
        Boolean,
      ) as string[];
    case "resource":
      return [
        n.data.type,
        n.data.initial && `initial ${n.data.initial}`,
        n.data.regen && `regen ${n.data.regen}`,
      ].filter(Boolean) as string[];
    case "content":
      return [n.data.type, count(n.data.rows.length, "row"), `priority ${n.data.priority}`];
    default:
      return [];
  }
}

function nodeLists(n: DesignNode): string[] {
  const lines: string[] = [];
  if (n.kind === "service" || n.kind === "layer" || n.kind === "module") {
    if (n.data.responsibilities.length > 0)
      lines.push(`Responsibilities: ${n.data.responsibilities.join("; ")}`);
  }
  if (n.kind === "layer" && n.data.rules.length > 0)
    lines.push(`Rules: ${n.data.rules.join("; ")}`);
  if (n.kind === "module" && n.data.exports.length > 0) {
    lines.push(`Exports: ${n.data.exports.map((e) => `\`${e}\``).join(", ")}`);
  }
  if (n.kind === "loop") {
    if (n.data.motivation.trim()) lines.push(`Motivation: ${oneLine(n.data.motivation)}`);
    if (n.data.steps.length > 0) lines.push(`Steps: ${n.data.steps.join(" → ")}`);
  }
  if (n.kind === "system" && n.data.purpose.trim())
    lines.push(`Purpose: ${oneLine(n.data.purpose)}`);
  if (n.kind === "mechanic" && n.data.states.length > 0) {
    lines.push(`States: ${n.data.states.join(" → ")}`);
  }
  if (n.kind === "system" || n.kind === "mechanic") {
    if (n.data.rules.length > 0) lines.push(`Rules: ${n.data.rules.join("; ")}`);
    if (n.data.parameters.length > 0) {
      lines.push(`Parameters: ${n.data.parameters.map(formatParameter).join("; ")}`);
    }
    for (const f of n.data.formulas) {
      lines.push(
        `Formula ${f.name}: \`${f.expression}\`${f.notes.trim() ? ` — ${oneLine(f.notes)}` : ""}`,
      );
    }
  }
  if (n.kind === "resource") {
    const range = [n.data.min && `min ${n.data.min}`, n.data.max && `max ${n.data.max}`].filter(
      Boolean,
    );
    if (range.length > 0) lines.push(`Range: ${range.join(", ")}`);
  }
  if (n.kind === "content" && n.data.columns.length > 0) {
    lines.push(`Columns: ${n.data.columns.join(" | ")} (rows under Content tables)`);
  }
  return lines;
}

function nodeRelations(index: DesignIndex, n: DesignNode): string[] {
  const name = (id: string) => index.node(id)?.name ?? id;
  const group = (label: string, items: string[]) =>
    items.length > 0 ? `${label}: ${items.join(", ")}` : "";

  const channel = (target: string, id: string | null) => {
    const q = index.node(target);
    const ch = q?.kind === "queue" ? q.data.channels.find((c) => c.id === id) : undefined;
    return ch ? `${name(target)}/${ch.name}` : name(target);
  };
  return [
    group(
      "Depends on",
      index.outgoing(n.id, "depends_on").map((e) => name(e.target)),
    ),
    group(
      "Calls",
      index.outgoing(n.id, "calls").map((e) => {
        const api = index.node(e.target);
        const ops =
          api?.kind === "api"
            ? e.data.operations
                .map((id) => api.data.operations.find((o) => o.id === id)?.name)
                .filter(Boolean)
            : [];
        return `${name(e.target)}${ops.length > 0 ? ` (${ops.join(", ")})` : ""} over ${e.data.protocol}`;
      }),
    ),
    group(
      "Exposes",
      index.outgoing(n.id, "exposes").map((e) => {
        const api = index.node(e.target);
        const ops =
          api?.kind === "api"
            ? e.data.operations
                .map((id) => api.data.operations.find((o) => o.id === id)?.name)
                .filter(Boolean)
            : [];
        return `${name(e.target)}${ops.length > 0 ? ` (${ops.join(", ")})` : ""}`;
      }),
    ),
    group(
      "Accesses",
      index.outgoing(n.id, "accesses").map((e) => `${name(e.target)} (${e.data.mode})`),
    ),
    group(
      "Publishes",
      index.outgoing(n.id, "publishes").map((e) => channel(e.target, e.data.channelId)),
    ),
    group(
      "Subscribes",
      index.outgoing(n.id, "subscribes").map((e) => channel(e.target, e.data.channelId)),
    ),
    group(
      "Uses",
      index
        .outgoing(n.id, "uses")
        .map((e) => `${name(e.target)}${e.data.purpose ? ` (${oneLine(e.data.purpose)})` : ""}`),
    ),
    group(
      "Drives",
      index.outgoing(n.id, "drives").map((e) => name(e.target)),
    ),
    group(
      "Produces",
      index
        .outgoing(n.id, "produces")
        .map((e) => `${name(e.target)}${e.data.rate ? ` (${e.data.rate})` : ""}`),
    ),
    group(
      "Consumes",
      index
        .outgoing(n.id, "consumes")
        .map((e) => `${name(e.target)}${e.data.amount ? ` (${e.data.amount})` : ""}`),
    ),
    group(
      "Triggers",
      index
        .outgoing(n.id, "triggers")
        .map((e) => `${name(e.target)}${e.data.event ? ` on ${e.data.event}` : ""}`),
    ),
    group(
      "Modifies",
      index
        .outgoing(n.id, "modifies")
        .map((e) => `${name(e.target)}${e.data.effect ? ` (${e.data.effect})` : ""}`),
    ),
  ].filter(Boolean);
}
